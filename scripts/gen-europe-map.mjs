/**
 * Generates apps/web/src/map/europe.gen.ts from world-atlas (Natural Earth
 * 50m) — build-time only, zero runtime dependency, fully offline.
 * Run: node scripts/gen-europe-map.mjs  (re-run only if the country set changes)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { geoAzimuthalEqualArea, geoCentroid, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const topo = require("world-atlas/countries-50m.json");
const world = feature(topo, topo.objects.countries);

const EUROPE = new Set([
  "France", "Belgium", "Netherlands", "Luxembourg", "Germany", "Spain", "Portugal",
  "Italy", "Switzerland", "Austria", "United Kingdom", "Ireland", "Denmark",
  "Norway", "Sweden", "Finland", "Iceland", "Poland", "Czechia", "Slovakia",
  "Hungary", "Slovenia", "Croatia", "Bosnia and Herz.", "Serbia", "Montenegro",
  "Albania", "North Macedonia", "Macedonia", "Greece", "Romania", "Bulgaria",
  "Estonia", "Latvia", "Lithuania", "Moldova", "Turkey", "Cyprus", "Malta", "Kosovo",
]);

// bbox Europe : élimine les territoires d'outre-mer (Guyane, Antilles, Canaries…)
// inclus dans les MultiPolygons de Natural Earth, qui écrasent le cadrage.
const IN_EUROPE = ([lon, lat]) => lon >= -25 && lon <= 46 && lat >= 30 && lat <= 72;

function clipToEurope(f) {
  const g = f.geometry;
  if (g.type === "Polygon") return IN_EUROPE(geoCentroid(f)) ? f : null;
  const polys = g.coordinates.filter((coords) =>
    IN_EUROPE(geoCentroid({ type: "Polygon", coordinates: coords }))
  );
  if (polys.length === 0) return null;
  return { ...f, geometry: { type: "MultiPolygon", coordinates: polys } };
}

const feats = world.features
  .filter((f) => EUROPE.has(f.properties.name))
  .map(clipToEurope)
  .filter(Boolean);
const found = new Set(feats.map((f) => f.properties.name));
for (const n of EUROPE) if (!found.has(n) && n !== "Macedonia") console.warn(`(absent de world-atlas: ${n})`);

const W = 720, H = 600;
const projection = geoAzimuthalEqualArea()
  .rotate([-10, -52])
  .fitExtent([[8, 8], [W - 8, H - 8]], { type: "FeatureCollection", features: feats });
const pathGen = geoPath(projection);

const round = (d) => d.replace(/(\d+\.\d{1})\d+/g, "$1");
const entries = feats.map((f) => {
  const name = f.properties.name === "Macedonia" ? "North Macedonia" : f.properties.name;
  const [cx, cy] = pathGen.centroid(f);
  return { name, d: round(pathGen(f)), cx: Math.round(cx * 10) / 10, cy: Math.round(cy * 10) / 10 };
});

const out = `// GENERATED by scripts/gen-europe-map.mjs — do not edit by hand.
// Natural Earth 50m via world-atlas, azimuthal equal-area projection centered on Europe.
export interface CountryShape {
  name: string;
  d: string;
  cx: number;
  cy: number;
}

export const MAP_W = ${W};
export const MAP_H = ${H};

export const EUROPE_COUNTRIES: CountryShape[] = ${JSON.stringify(entries, null, 1)};
`;

const dest = path.join(ROOT, "apps/web/src/map/europe.gen.ts");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`✔ ${dest} — ${entries.length} pays, ${Math.round(out.length / 1024)} Ko`);
